test_vpkuhus_aliased_all:
  # vD == vA == vB: every lane packs the original halfwords.
  # {1, 256, 255, 32767, 2, 65535, 256, 128}
  #_ REGISTER_IN v3 [00010100, 00FF7FFF, 0002FFFF, 01000080]
  vpkuhus v3, v3, v3
  blr
  #_ REGISTER_OUT v3 [01FFFFFF, 02FFFF80, 01FFFFFF, 02FFFF80]

